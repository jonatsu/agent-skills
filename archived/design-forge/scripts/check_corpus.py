def strip_comment(value: str) -> str:
    """Drop a trailing ``#`` comment that is not inside quotes.

    Args:
        value: One raw frontmatter value, possibly with a trailing comment.

    Returns:
        The value with any unquoted trailing comment removed and whitespace
        stripped.
    """
    out: list[str] = []
    quote: str | None = None
    prev_space = True
    for char in value:
        if quote is not None:
            out.append(char)
            if char == quote:
                quote = None
        elif char in "\"'":
            quote = char
            out.append(char)
        elif char == "#" and prev_space:
            break
        else:
            out.append(char)
        prev_space = char.isspace()
    return "".join(out).strip()


def coerce_scalar(text: str) -> Scalar:
    """Turn already-comment-stripped text into a bool or a string.

    Only ``true`` and ``false`` become booleans. Everything else stays a
    string, with one layer of matched quotes removed. Numbers stay strings
    because no contract field is numeric.
    """
    if text in ("true", "false"):
        return text == "true"
    if len(text) >= 2 and text[0] == text[-1] and text[0] in "\"'":
        return text[1:-1]
    return text


def parse_value(raw: str) -> FrontValue:
    """Parse one ``key:`` value, which may be an inline list.

    Args:
        raw: Everything after the first colon on a frontmatter line.

    Returns:
        A scalar, or a flat list of scalars for ``[a, b]`` syntax. Nesting is
        not supported and is not attempted -- an inner bracket stays a string.
    """
    text = strip_comment(raw)
    if text.startswith("[") and text.endswith("]"):
        inner = text[1:-1].strip()
        if not inner:
            return []
        return [coerce_scalar(part.strip()) for part in inner.split(",")]
    return coerce_scalar(text)


def split_frontmatter(lines: list[str]) -> tuple[str, list[str], int]:
    """Locate the frontmatter block.

    Args:
        lines: The document's newline-stripped lines.

    Returns:
        ``(status, block_lines, body_start)`` where status is ``ok``,
        ``absent`` when the file does not open with ``---``, or
        ``unterminated`` when it opens one that never closes.
    """
    if not lines or lines[0].rstrip("\n") != "---":
        return "absent", [], 0
    for index in range(1, len(lines)):
        if lines[index].rstrip("\n") == "---":
            return "ok", lines[1:index], index + 1
    return "unterminated", [], 0


def parse_frontmatter(block: list[str]) -> tuple[Frontmatter, list[str]]:
    """Parse the restricted frontmatter subset, failing closed.

    Anything outside the contract's shapes -- a nested mapping, a multi-line
    scalar, an anchor -- is reported by line number rather than guessed at. A
    document with parse errors is still checked for everything else, so one
    stray line does not suppress the rest of its findings.

    Args:
        block: The lines between the two ``---`` markers.

    Returns:
        ``(fields, errors)``. The field map holds whatever parsed cleanly.
    """
    fields: Frontmatter = {}
    errors: list[str] = []
    pending: str | None = None
    for offset, raw in enumerate(block):
        lineno = offset + 2
        line = raw.rstrip("\n")
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        stripped = line.strip()
        if stripped.startswith("- "):
            if pending is None:
                errors.append(f"line {lineno}: list item with no key above it")
                continue
            bucket = fields[pending]
            if isinstance(bucket, list):
                bucket.append(coerce_scalar(strip_comment(stripped[2:])))
            continue
        if line[0].isspace():
            errors.append(f"line {lineno}: unsupported indented line {stripped!r}")
            pending = None
            continue
        if ":" not in line:
            errors.append(f"line {lineno}: not a `key: value` pair")
            pending = None
            continue
        name, _, rest = line.partition(":")
        name = name.strip()
        if strip_comment(rest) == "":
            fields[name] = []
            pending = name
        else:
            fields[name] = parse_value(rest)
            pending = None
    return fields, errors


