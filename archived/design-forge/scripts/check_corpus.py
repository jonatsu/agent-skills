def git_show(rev: str, path: Path) -> tuple[str | None, str | None]:
    """Read a file as of ``rev``, returning ``(text, problem)``.

    Git is the only external dependency in this script and it is reachable
    only from here. Its absence is reported and the check is skipped, never
    silently passed -- a verification that quietly does nothing is worse than
    one that is not run at all.
    """
    if shutil.which("git") is None:
        return None, "git is not on PATH; the fork check was SKIPPED, not passed"
    try:
        proc = subprocess.run(  # noqa: S603
            ["git", "show", f"{rev}:./{path.name}"],
            cwd=path.parent if str(path.parent) else ".",
            capture_output=True,
            text=True,
            check=False,
        )
    except OSError as exc:
        return None, f"cannot run git ({exc})"
    if proc.returncode != 0:
        return None, f"git show {rev}:{path} failed: {proc.stderr.strip()}"
    return proc.stdout, None


def parent_is_dirty(parent: Path) -> bool:
    """Whether ``parent`` has uncommitted changes.

    A fork is normally performed in the document you were just editing, so the
    parent is usually dirty and ``--since HEAD`` then compares the child against
    a version that predates the session. That produces a mismatch on a correct
    relocation, which reads as a botched fork. Knowing this lets the mismatch
    explain itself; it is never a failure on its own, because a parent whose
    edits fell outside the moved section compares perfectly well.
    """
    if shutil.which("git") is None:
        return False
    try:
        proc = subprocess.run(  # noqa: S603
            ["git", "status", "--porcelain", "--", parent.name],
            cwd=parent.parent if str(parent.parent) else ".",
            capture_output=True,
            text=True,
            check=False,
        )
    except OSError:
        return False
    return proc.returncode == 0 and bool(proc.stdout.strip())


def extract_section(lines: list[str], heading: str) -> list[str] | None:
    """Return the named ``##`` section including its heading, or None.

    A deeper heading does not end the section: ``### Foo`` is content inside
    it, and treating it as a boundary would silently compare a fragment and
    call the fork verified.
    """
    want = heading.strip()
    start: int | None = None
    for index, line in enumerate(lines):
        if start is None:
            if line.strip() == want:
                start = index
        elif line.startswith("## "):
            return lines[start:index]
    return None if start is None else lines[start:]


def trim_blanks(lines: list[str]) -> list[str]:
    """Drop leading and trailing blank lines.

    Hygiene hooks trim trailing whitespace and fix end-of-file newlines after
    a fork has already moved the text, and a section relocated to the end of a
    file predictably loses the blank that separated it from the next heading.
    Those are formatter artifacts. A changed word is not, and still fails.
    """
    start = 0
    end = len(lines)
    while start < end and not lines[start].strip():
        start += 1
    while end > start and not lines[end - 1].strip():
        end -= 1
    return lines[start:end]


MARKDOWN_LINK = re.compile(r"\[[^\]]*\]\(([^)]+)\)")


def section_is_fork_pointer(section: list[str], child: Path) -> bool:
    """Whether ``section`` is the pointer a completed fork leaves behind.

    The second wrong-baseline case. Running the check *after* committing the
    fork reads a parent whose section is already the retained heading plus a
    pointer, so the comparison is against the wrong revision again -- and the
    parent is clean, so the dirty-tree hint correctly stays quiet.

    The test requires the body to be nothing but a blockquote *and* to link to
    the child being compared. Both together make it conclusive rather than
    likely: a section that quotes a specification is all-blockquote too, and
    would otherwise be accused of being a pointer.
    """
    body = trim_blanks(section[1:])
    if not body:
        return False
    if any(line.strip() and not line.lstrip().startswith(">") for line in body):
        return False
    targets = {Path(target).name for line in body for target in MARKDOWN_LINK.findall(line)}
    return child.name in targets


def verify_fork(spec: str, child: Path, rev: str, report: Report) -> bool:
    """Check that a forked section arrived byte-identical.

    Args:
        spec: ``PARENT.md:## Section`` -- the source file and the heading that
            moved out of it.
        child: The document the section moved into.
        rev: The revision to read the parent at, before the fork.
        report: Collector for every problem found.

    Returns:
        Whether the relocation verified. Reading a ``git diff`` by eye does not
        work for the sequence conversion prescribes: the child is untracked,
        the parent's diff also carries the frontmatter the previous step added,
        and the retained heading is coalesced as context. All three read as a
        mismatch on a correct fork, which is why this exists.
    """
    parent_raw, sep, heading = spec.partition(":")
    if not sep or not heading.strip() or not parent_raw:
        report.error(f"--verify-fork needs PARENT.md:'## Section'; got {spec!r}")
        return False
    parent = Path(parent_raw)
    dirty = parent_is_dirty(parent)
    already_forked = False

    def baseline_hint() -> None:
        """Explain a failure that the comparison baseline, not the fork, caused.

        Two causes, and the more specific one wins: a parent already carrying
        the pointer is conclusive, where a dirty parent is only likely.
        """
        if already_forked:
            report.warn(
                f"{parent} at {rev} already carries the fork pointer to {child.name}, so "
                f"the section had moved out of it by that revision and there was nothing "
                f"left to compare against. Pass --since a revision from BEFORE the fork."
            )
        elif dirty:
            report.warn(
                f"{parent} has uncommitted changes, so --since {rev} compared the child "
                f"against the COMMITTED version, not the one the section was forked out "
                f"of. Commit the parent's pre-fork state and re-run, or pass --since with "
                f"a revision that has it."
            )

    text, problem = git_show(rev, parent)
    if text is None:
        report.error(problem or f"cannot read {parent} at {rev}")
        baseline_hint()
        return False
    section = extract_section(text.splitlines(), heading)
    if section is None:
        report.error(f"{parent} at {rev}: no section {heading.strip()!r}")
        baseline_hint()
        return False
    already_forked = section_is_fork_pointer(section, child)
    try:
        child_lines = child.read_text(encoding="utf-8").splitlines()
    except (OSError, UnicodeDecodeError) as exc:
        report.error(f"{child}: cannot read ({exc})")
        baseline_hint()
        return False
    _, _, body_start = split_frontmatter(child_lines)
    want = trim_blanks(section)
    have = trim_blanks(child_lines[body_start:])
    for number, (left, right) in enumerate(zip(want, have, strict=False), start=1):
        if left != right:
            report.error(
                f"fork mismatch at body line {number}: {parent} has {left!r}, {child} has {right!r}"
            )
            baseline_hint()
            return False
    if len(want) != len(have):
        report.error(
            f"fork mismatch: the section in {parent} is {len(want)} lines, "
            f"the body of {child} is {len(have)}"
        )
        baseline_hint()
        return False
    print(f"fork verified: {len(want)} lines identical")
    return True


